#!/usr/bin/env python3
"""Generate include/aprs_symbols.h: 24x24 PNG icons for the APRS primary (/) and
alternate (\\) symbol tables, cut from the aprs.fi symbol set by Heikki Hannikainen
OH7LZB, https://github.com/hessu/aprs-symbols (see that repository for licensing).

Usage: gen_aprs_symbols.py <dir with aprs-symbols-24-0.png and -1.png> <output .h>
Icons are served by the web UI at /symbols/icons/<ascii>-<1|2>.png, so the UI
works without internet.
"""
import io, sys
from PIL import Image, ImageDraw

src, out = sys.argv[1], sys.argv[2]
blobs, index = [], []
for table in (0, 1):
    im = Image.open(f'{src}/aprs-symbols-24-{table}.png').convert('RGBA')
    for idx in range(96):                      # ASCII 33..128, 16 per row
        c, r = idx % 16, idx // 16
        tile = im.crop((c * 24, r * 24, c * 24 + 24, r * 24 + 24))
        b = io.BytesIO(); tile.save(b, 'PNG', optimize=True)
        index.append((33 + idx, table + 1, len(blobs)))
        blobs.append(b.getvalue())
dot = Image.new('RGBA', (24, 24), (0, 0, 0, 0))
ImageDraw.Draw(dot).ellipse((8, 8, 15, 15), fill=(90, 90, 90, 255))
b = io.BytesIO(); dot.save(b, 'PNG', optimize=True); dot_blob = b.getvalue()

with open(out, 'w') as f:
    f.write('// Generated by tools/gen_aprs_symbols.py - do not edit.\n')
    f.write('// APRS symbols: aprs.fi symbol set, https://github.com/hessu/aprs-symbols\n')
    f.write('#pragma once\n#include <Arduino.h>\n\n')
    data = b''.join(blobs)
    offs, o = [], 0
    for bl in blobs:
        offs.append(o); o += len(bl)
    f.write(f'static const uint8_t aprs_sym_data[{len(data)}] PROGMEM = {{\n')
    for i in range(0, len(data), 24):
        f.write(','.join(str(x) for x in data[i:i + 24]) + ',\n')
    f.write('};\n')
    f.write(f'// offset/length per icon, index = (table-1)*96 + (ascii-33)\n')
    f.write(f'static const uint32_t aprs_sym_off[{len(blobs)}] PROGMEM = {{{",".join(map(str, offs))}}};\n')
    f.write(f'static const uint16_t aprs_sym_len[{len(blobs)}] PROGMEM = {{{",".join(str(len(b)) for b in blobs)}}};\n')
    f.write(f'static const uint8_t aprs_sym_dot[{len(dot_blob)}] PROGMEM = {{{",".join(map(str, dot_blob))}}};\n')
print('icons', len(blobs), 'bytes', sum(map(len, blobs)) + len(dot_blob))
